// Turns scripts/car-specs.mjs into car-table rows keyed by EXACT FuelEconomy.gov names
// (year + make + model + trim/engine), so customer picks match the table.
// Writes src/data/car-table.json (local demo seed) and supabase/seed_car_table.sql.
//   node scripts/build-car-table.mjs
import { writeFile, mkdir } from 'node:fs/promises';
import { SPECS } from './car-specs.mjs';

const FE = 'https://www.fueleconomy.gov/ws/rest/vehicle';
const SKIP_MODEL = /hybrid|plug-in|electric|\bEV\b|natural gas|CNG|FCV|PHEV|e-tron|Energi/i;
const SKIP_OPTION = /diesel|CNG|electric/i;

const cache = new Map();
async function get(path) {
  if (cache.has(path)) return cache.get(path);
  const p = (async () => {
    for (let n = 1; ; n++) {
      try {
        const r = await fetch(`${FE}/${path}`, { headers: { Accept: 'application/json' } });
        if (!r.ok) throw new Error(String(r.status));
        const t = await r.text();
        const i = t ? JSON.parse(t)?.menuItem : null;
        return i ? (Array.isArray(i) ? i : [i]) : [];
      } catch (e) {
        if (n >= 4) throw e;
        await new Promise((r) => setTimeout(r, 600 * n));
      }
    }
  })();
  cache.set(path, p);
  return p;
}
async function pool(items, size, fn) {
  const q = [...items];
  await Promise.all(Array.from({ length: size }, async () => { while (q.length) await fn(q.shift()); }));
}

const thisYear = new Date().getFullYear();
const rows = new Map();
const report = [];

await pool(SPECS, 6, async (spec) => {
  const [make, modelRe, from, to, displ, turbo, litres, grade, opts = {}] = spec;
  let hits = 0;
  for (let year = from; year <= Math.min(to, thisYear + 1); year++) {
    const models = await get(`menu/model?${new URLSearchParams({ year, make })}`).catch(() => []);
    for (const m of models) {
      if (!modelRe.test(m.value)) continue;
      if (!opts.allowHybrid && SKIP_MODEL.test(m.value)) continue;
      const options = await get(`menu/options?${new URLSearchParams({ year, make, model: m.value })}`).catch(() => []);
      for (const o of options) {
        if (SKIP_OPTION.test(o.text)) continue;
        if (!o.text.includes(`${displ.toFixed(1)} L`)) continue;
        if (/Turbo/i.test(o.text) !== turbo) continue;
        const key = [year, make, m.value, o.text].join('|').toLowerCase();
        rows.set(key, {
          year: String(year), make, model: m.value, trim: o.text, fe_id: o.value,
          oil_litres: litres, oil_grade: grade, filter_price: null, quote_only: false,
          notes: 'Starter spec, verify',
        });
        hits++;
      }
    }
  }
  report.push(`${hits ? '  ' : '!!'} ${String(hits).padStart(3)}  ${make} ${modelRe} ${from}-${to} ${displ}${turbo ? 'T' : ''}`);
});

const list = [...rows.values()].sort((a, b) =>
  `${a.make} ${a.model} ${a.year} ${a.trim}`.localeCompare(`${b.make} ${b.model} ${b.year} ${b.trim}`));
console.log(report.sort().join('\n'));
console.log(`\n${list.length} car-table rows from ${SPECS.length} specs`);

await mkdir(new URL('../src/data/', import.meta.url), { recursive: true });
await writeFile(new URL('../src/data/car-table.json', import.meta.url), JSON.stringify(list));

const q = (v) => (v == null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const sql = [
  "-- Starter car table generated by scripts/build-car-table.mjs. Specs are typical values: verify.",
  '-- Run after 001_init.sql. Existing rows (same year/make/model/trim) are left untouched.',
  'insert into car_table (year, make, model, trim, fe_id, oil_litres, oil_grade, filter_price, quote_only, notes) values',
  list.map((r) => `(${[r.year, r.make, r.model, r.trim, r.fe_id, r.oil_litres, r.oil_grade, r.filter_price, r.quote_only, r.notes].map(q).join(', ')})`).join(',\n'),
  'on conflict (lower(year), lower(make), lower(model), lower(trim)) do nothing;',
  '',
].join('\n');
await writeFile(new URL('../supabase/seed_car_table.sql', import.meta.url), sql);
console.log('Wrote src/data/car-table.json and supabase/seed_car_table.sql');
